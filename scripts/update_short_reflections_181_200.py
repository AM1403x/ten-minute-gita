def main():
    # Path to the JSON file
    json_file = Path(__file__).parent.parent / "data" / "gita_snippets_hindi.json"

    if not json_file.exists():
        print(f"Error: File not found at {json_file}")
        sys.exit(1)

    # Read the JSON file
    print(f"Reading {json_file}...")
    with open(json_file, 'r', encoding='utf-8') as f:
        data = json.load(f)

    # Update shortReflection for snippets 181-200
    updated_count = 0
    for snippet in data['snippets']:
        if 181 <= snippet['id'] <= 200:
            snippet_id = snippet['id']
            if snippet_id in SHORT_REFLECTIONS:
                snippet['shortReflection'] = SHORT_REFLECTIONS[snippet_id]
                updated_count += 1
                print(f"Updated snippet {snippet_id}")

    # Write back to the file
    print(f"\nWriting updated data back to {json_file}...")
    with open(json_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"\n✓ Successfully updated {updated_count} snippets (181-200)")
    print("All shortReflection fields have been added/updated.")

if __name__ == "__main__":
    main()
