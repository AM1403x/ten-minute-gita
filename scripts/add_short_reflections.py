def main():
    input_file = "/Users/anishmoonka/gita-app/data/gita_snippets_hindi.json"

    print(f"Reading {input_file}...")
    with open(input_file, 'r', encoding='utf-8') as f:
        data = json.load(f)

    if 'snippets' not in data:
        print("Error: 'snippets' key not found in JSON")
        sys.exit(1)

    snippets = data['snippets']
    print(f"Found {len(snippets)} snippets")

    # Update snippets 1-20
    updated_count = 0
    for snippet in snippets:
        snippet_id = snippet.get('id')
        if snippet_id and 1 <= snippet_id <= 20:
            if snippet_id in SHORT_REFLECTIONS:
                snippet['shortReflection'] = SHORT_REFLECTIONS[snippet_id]
                updated_count += 1
                print(f"Updated snippet {snippet_id}")

    print(f"\nUpdated {updated_count} snippets with shortReflection")

    # Write back to file
    print(f"Writing to {input_file}...")
    with open(input_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print("Done!")

if __name__ == '__main__':
    main()
